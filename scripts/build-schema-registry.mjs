import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { basename } from 'node:path';

const root = new URL('../', import.meta.url);
const outDir = new URL('../web/', import.meta.url);
const out = new URL('../web/schemaRegistry.mjs', import.meta.url);

async function readJson(relativePath) {
  return JSON.parse(await readFile(new URL(relativePath, root), 'utf8'));
}

const entries = [];
const core = await readJson('schema/v0.1/core.schema.json');
entries.push([core.$id, core]);
entries.push([
  'https://ticketschema.org/schema/v0.1/core.schema.json',
  { ...core, $id: 'https://ticketschema.org/schema/v0.1/core.schema.json' },
]);

const profileFiles = [
  'delivery-note.schema.json',
  'loan-note.schema.json',
  'payment-receipt.schema.json',
  'payment-request.schema.json',
  'retail-receipt.schema.json',
  'service-record.schema.json',
];

for (const file of profileFiles) {
  const schema = await readJson(`schema/v0.1/profiles/${file}`);
  entries.push([
    `https://ticketschema.org/schema/v0.1/profiles/${basename(file).replace('.schema.json', '.json')}`,
    schema,
  ]);
}

await mkdir(outDir, { recursive: true });
await writeFile(
  out,
  `// Generated by scripts/build-schema-registry.mjs\nexport const schemas = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`
);
